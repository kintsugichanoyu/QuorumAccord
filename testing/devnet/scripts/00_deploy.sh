#!/usr/bin/env bash
# Build + deploy both programs to devnet, generate keypairs, and write .env.devnet.
# Run from anywhere; requires solana-cli + anchor (Solana 2.1 / Anchor 1.0.2).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
cd "$ROOT"

CLUSTER_URL="${SOLANA_RPC_URL:-https://api.devnet.solana.com}"
KEYS_DIR="$ROOT/testing/devnet/.state/keys"
mkdir -p "$KEYS_DIR"

echo "==> solana config -> $CLUSTER_URL"
solana config set --url "$CLUSTER_URL" >/dev/null

echo "==> keypairs"
for name in admin op1 op2 op3 outsider; do
  f="$KEYS_DIR/$name.json"
  if [[ ! -f "$f" ]]; then
    solana-keygen new --no-bip39-passphrase --silent --force -o "$f" >/dev/null
    echo "   generated $name -> $(solana-keygen pubkey "$f")"
  else
    echo "   reuse     $name -> $(solana-keygen pubkey "$f")"
  fi
done
ADMIN_PUBKEY="$(solana-keygen pubkey "$KEYS_DIR/admin.json")"

# Deploying two BPF programs needs several SOL of rent; devnet airdrops cap at
# 2 SOL/request and are rate-limited, so try a few times and warn if short.
echo "==> fund admin ($ADMIN_PUBKEY) — targeting ~6 SOL for two deploys"
for _ in 1 2 3; do
  solana airdrop 2 "$ADMIN_PUBKEY" --url "$CLUSTER_URL" || true
  bal="$(solana balance "$ADMIN_PUBKEY" --url "$CLUSTER_URL" | awk '{print $1}')"
  awk "BEGIN{exit !($bal >= 6)}" && break
  sleep 2
done
echo "   admin balance: $(solana balance "$ADMIN_PUBKEY" --url "$CLUSTER_URL")"

echo "==> anchor build"
anchor build
echo "==> anchor keys sync (rewrites declare_id! + Anchor.toml from target/deploy keypairs)"
anchor keys sync
echo "==> anchor build (after keys sync)"
anchor build

echo "==> anchor deploy (devnet, payer = admin)"
anchor deploy --provider.cluster devnet --provider.wallet "$KEYS_DIR/admin.json"

REFLECT_ID="$(anchor keys list | awk '/reflect_allocation/{print $2}')"
MOCK_ID="$(anchor keys list | awk '/mock_oracle/{print $2}')"
echo "   reflect_allocation = $REFLECT_ID"
echo "   mock_oracle        = $MOCK_ID"

cat > "$ROOT/.env.devnet" <<EOF
# generated by scripts/devnet/00_deploy.sh on $(date -u +%FT%TZ)
SOLANA_RPC_URL=$CLUSTER_URL
PROGRAM_ID=$REFLECT_ID
MOCK_PROGRAM_ID=$MOCK_ID
ADMIN_KEYPAIR=$KEYS_DIR/admin.json
OP_KEYPAIRS=$KEYS_DIR/op1.json,$KEYS_DIR/op2.json,$KEYS_DIR/op3.json
OUTSIDER_KEYPAIR=$KEYS_DIR/outsider.json
ROUND=0
STALENESS_SLOTS=1000000
RUST_LOG=info
EOF

echo "==> wrote $ROOT/.env.devnet"
echo
echo "Next (deterministic path):"
echo "   set -a; source .env.devnet; set +a"
echo "   cd workers && cargo run -p e2e -- run-happy"
echo "   cd workers && cargo run -p e2e -- run-invariants"
echo "Or the daemon path: bash scripts/devnet/run_e2e.sh"
